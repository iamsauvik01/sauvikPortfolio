// Rough frame-rate check of the island (overview + a busy close-up).
import { chromium } from 'playwright-core'
const W = Number(process.argv[2] || 1440), H = Number(process.argv[3] || 900)
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] })
const page = await (await browser.newContext({ viewport: { width: W, height: H } })).newPage()
await page.goto(process.env.URL || 'http://localhost:5173/')
await page.waitForFunction(() => !document.querySelector('[aria-label="Loading the little world"]'), null, { timeout: 30000 })
await new Promise((r) => setTimeout(r, 2500))
const fps = () => page.evaluate(() => new Promise((res) => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 3000) requestAnimationFrame(f); else res((n / 3).toFixed(1)) }; requestAnimationFrame(f) }))
console.log('landing fps', await fps())
await page.locator('button.cta').click()
await new Promise((r) => setTimeout(r, 7500))
await page.locator('.btn-ghost').first().click()
await new Promise((r) => setTimeout(r, 1500))
console.log('island overview fps', await fps())
await page.evaluate(() => window.__bit.islandStore.set({ focus: 'workshop' }))
await new Promise((r) => setTimeout(r, 3000))
console.log('workshop fps', await fps())
console.log('renderer', await page.evaluate(() => { const g = window.__island.gl; return JSON.stringify({ calls: g.info.render.calls, tris: g.info.render.triangles, programs: g.info.programs.length, dpr: g.getPixelRatio() }) }))
await browser.close()
